def _norm(s: str) -> str:
    return str(s).strip().lower().replace(" ", "_").replace("-", "_")


def _detect_columns(fieldnames: List[str]) -> Dict[str, str]:
    """Map canonical field -> actual column name."""
    lookup = {_norm(f): f for f in fieldnames}
    found: Dict[str, str] = {}
    for canon, aliases in _COL_ALIASES.items():
        for a in aliases:
            if _norm(a) in lookup:
                found[canon] = lookup[_norm(a)]
                break
    return found


# --------------------------------------------------------------------------
# Time parsing
# --------------------------------------------------------------------------
def parse_time(val: Any) -> float:
    """Parse ISO / epoch / numeric time to UTC epoch seconds."""
    if val is None or val == "":
        return 0.0
    if isinstance(val, (int, float)):
        return float(val)
    s = str(val).strip()
    # epoch seconds (10 or 13 digits)
    if s.isdigit() and len(s) in (10, 13):
        v = float(s)
        return v / 1000.0 if len(s) == 13 else v
    # ISO with T and Z
    import calendar
    import time as _time
    for fmt in ("%Y-%m-%dT%H:%M:%SZ", "%Y-%m-%dT%H:%M:%S",
                "%Y-%m-%d %H:%M:%S", "%Y-%m-%d %H:%M", "%Y-%m-%d"):
        try:
            return float(calendar.timegm(_time.strptime(s, fmt)))
        except ValueError:
            continue
    # try fromisoformat (handles offsets)
    try:
        import datetime as _dt
        dt = _dt.datetime.fromisoformat(s.replace("Z", "+00:00"))
        return dt.timestamp()
    except ValueError:
        return 0.0


# --------------------------------------------------------------------------
# Trade record
# --------------------------------------------------------------------------
@dataclass
class Trade:
    symbol: str
    direction: str          # BUY | SELL
    entry_time: float       # epoch
    exit_time: float
    entry_price: float
    exit_price: float
    lots: float
    pnl: float
    broker: str = ""
    account: str = ""
    entry_type: str = ""
    entry_quality: float = 0.5

    @property
    def realised_return(self) -> float:
        """Signed price move over the holding period (exit - entry)."""
        return self.exit_price - self.entry_price


def market_return_for_trade(t: Trade) -> float:
    """Positive when the *market* moved up, regardless of trade side.

    A SELL profit is a down market. When prices are missing, the PnL sign is
    used as a trade-direction-relative return and converted to market space.
    """
    # Neural labels represent MARKET direction, not side-relative profit.
    # Profitable SELL on falling prices -> DOWN (0), not UP (1).
    # Net broker PnL is separately used by the loss-pattern memory.
    if t.exit_price and t.entry_price:
        return t.exit_price - t.entry_price
    trade_relative = 1.0 if t.pnl > 0 else -1.0
    return trade_relative if t.direction == "BUY" else -trade_relative


def _to_dir(v: Any) -> str:
    s = _norm(v)
    if s in ("buy", "long", "b", "1"):
        return "BUY"
    if s in ("sell", "short", "s", "0", "-1"):
        return "SELL"
    return "BUY" if str(v).strip().upper().startswith("B") else "SELL"


def _to_float(v: Any) -> float:
    try:
        return float(v)
    except (TypeError, ValueError):
        return 0.0


def load_trade_file(path: str) -> List[Trade]:
    """Load trades from a CSV/CSV.gz or JSON file (auto-detected).

    MT5/broker native deal exports (rows per DEAL with entry_code/
    position_id) are reconstructed into closed trades; simple one-row-
    per-trade CSVs/JSON are read directly.
    """
    trades: List[Trade] = []
    ext = os.path.splitext(path)[1].lower()
    try:
        if ext in (".csv", ".txt", ".gz", ".csv.gz", ""):
            # peek header to detect MT5 deals format
            with _open_csv(path) as fh:
                fields = list(csv.DictReader(fh).fieldnames or [])
            if is_mt5_deals(fields):
                return load_mt5_deals(path)
            with _open_csv(path) as fh:
                reader = csv.DictReader(fh)
                cols = _detect_columns(list(reader.fieldnames or []))
                for row in reader:
                    t = _trade_from_row(row, cols)
                    if t:
                        trades.append(t)
        elif ext in (".json", ""):
            with open(path, encoding="utf-8") as fh:
                data = json.load(fh)
            for row in _flatten_json(data):
                cols = _detect_columns(list(row.keys()))
                t = _trade_from_row(row, cols)
                if t:
                    trades.append(t)
        else:
            # try CSV then JSON
            try:
                return load_trade_file(path.replace(ext, ".csv"))
            except Exception:
                return load_trade_file(path.replace(ext, ".json"))
    except Exception as exc:
        print(f"  ! could not read {path}: {exc}")
    return trades


def _flatten_json(data: Any) -> List[Dict[str, Any]]:
    """Flatten nested JSON (list of trades, or {account: [trades]})."""
    out: List[Dict[str, Any]] = []
    if isinstance(data, list):
        for item in data:
            if isinstance(item, dict):
                out.append(item)
    elif isinstance(data, dict):
        # could be {account: [trades]} or a single trade dict
        for k, v in data.items():
            if isinstance(v, list) and v and isinstance(v[0], dict):
                for item in v:
                    merged = dict(item)
                    merged.setdefault("account", k)
                    out.append(merged)
            elif isinstance(v, dict):
                merged = dict(v)
                merged.setdefault("account", k)
                out.append(merged)
        # also a bare trade dict
        if not out and all(isinstance(v, (str, int, float))
                           for v in data.values()):
            out.append(data)
    return out


def _trade_from_row(row: Dict[str, Any],
                    cols: Dict[str, str]) -> Optional[Trade]:
    if "symbol" not in cols or "entry_time" not in cols:
        return None
    sym = str(row.get(cols["symbol"], "")).strip()
    if not sym:
        return None
    # normalise symbol to universe form if possible
    sym = _match_symbol(sym)
    ep = _to_float(row.get(cols.get("entry_price", ""), 0))
    xp = _to_float(row.get(cols.get("exit_price", ""), 0))
    pnl = _to_float(row.get(cols.get("pnl", ""), 0))
    # derive exit price from pnl if missing
    if xp == 0.0 and ep != 0.0:
        # pnl sign depends on direction; approximate exit price
        won = pnl > 0
        d = _to_dir(row.get(cols.get("direction", ""), "BUY"))
        # we can't know the exact move without stop distance, so leave
        # realised_return to be derived from pnl sign below
    et = parse_time(row.get(cols["entry_time"], ""))
    xt = parse_time(row.get(cols.get("exit_time", ""), ""))
    if et == 0.0:
        return None
    return Trade(
        symbol=sym,
        direction=_to_dir(row.get(cols.get("direction", ""), "BUY")),
        entry_time=et, exit_time=xt,
        entry_price=ep, exit_price=xp,
        lots=_to_float(row.get(cols.get("lots", ""), 0)),
        pnl=pnl,
        broker=str(row.get(cols.get("broker", ""), "")),
        account=str(row.get(cols.get("account", ""), "")),
        entry_type=str(row.get(cols.get("entry_type", ""), "")),
        entry_quality=_to_float(row.get(cols.get("entry_quality", ""), 0.5))
        or 0.5,
    )


def _match_symbol(s: str) -> str:
    """Map an arbitrary symbol string to the canonical universe form."""
    s = s.strip()
    if s in SYMBOL_UNIVERSE:
        return s
    # case-insensitive match
    low = s.lower()
    for sym in SYMBOL_UNIVERSE:
        if sym.lower() == low:
            return sym
    # partial: e.g. 'EURUSD' -> 'EURUSD.r'
    for sym in SYMBOL_UNIVERSE:
        base = sym.split(".")[0].lower()
        if low.startswith(base) or base.startswith(low):
            return sym
    return s  # keep as-is; will be skipped if not in universe


# --------------------------------------------------------------------------
# MT5 / broker deals.csv reconstruction
# --------------------------------------------------------------------------
# Broker native deal exports (MT5) record one row per DEAL, not per trade:
# a position is an OPEN deal (entry_code=0) plus a CLOSE deal (entry_code=1)
# sharing a position_id. We pair them to reconstruct each closed trade.
# deal_type convention (verified 100% against profit/move agreement):
#   0 = BUY, 1 = SELL.
_MT5_DEAL_TYPE = {0: "BUY", 1: "SELL"}


def _open_csv(path: str):
    """Open a possibly-gzipped CSV for reading."""
    if path.endswith(".gz"):
        return gzip.open(path, "rt", encoding="utf-8-sig", newline="")
    return open(path, newline="", encoding="utf-8-sig")


def is_mt5_deals(fieldnames: List[str]) -> bool:
    return any(_norm(f) in ("entry_code", "position_id")
               for f in (fieldnames or []))


def load_mt5_deals(path: str) -> List[Trade]:
    """Reconstruct closed trades from an MT5/broker deals.csv(.gz)."""
    trades: List[Trade] = []
    broker = ""
    account = ""
    # derive broker/account from path: .../<Broker>/<ACCT>/deals.csv.gz
    parts = path.replace("\\", "/").split("/")
    if len(parts) >= 2:
        account = parts[-2]
        broker = parts[-3] if len(parts) >= 3 else ""
    opens: Dict[str, Dict[str, Any]] = {}
    with _open_csv(path) as fh:
        reader = csv.DictReader(fh)
        for row in reader:
            pos = str(row.get("position_id", "")).strip()
            try:
                entry_code = int(float(row.get("entry_code", "0") or 0))
            except (TypeError, ValueError):
                continue
            if entry_code == 0:  # open
                opens[pos] = {
                    "symbol": _match_symbol(row.get("symbol", "")),
                    "entry_time": parse_time(row.get("time_utc", "")),
                    "entry_price": _to_float(row.get("price", 0)),
                    "deal_type": int(float(row.get("deal_type_code", "0")
                                            or 0)),
                    "volume": _to_float(row.get("volume", 0)),
                }
            elif entry_code == 1:  # close
                o = opens.pop(pos, None)
                if o is None:
                    continue  # close with no matching open (skip)
                sym = o["symbol"]
                if sym not in SYMBOL_UNIVERSE:
                    continue
                trades.append(Trade(
                    symbol=sym,
                    direction=_MT5_DEAL_TYPE.get(o["deal_type"], "BUY"),
                    entry_time=o["entry_time"],
                    exit_time=parse_time(row.get("time_utc", "")),
                    entry_price=o["entry_price"],
                    exit_price=_to_float(row.get("price", 0)),
                    lots=o["volume"],
                    pnl=_to_float(row.get("profit", 0)),
                    broker=broker, account=account,
                    entry_type=str(row.get("entry_type", "")),
                    entry_quality=0.5,
                ))
    return trades


# --------------------------------------------------------------------------
# Market-data alignment with full causal signals
# --------------------------------------------------------------------------
class MarketAlign:
    """Map a settled trade to the exact feature row at its entry bar."""

    def __init__(self, data_dir: str, timeframe: str = "M5", *,
                 ticks_path: str = "", depth_path: str = "",
                 use_gemma: bool = False):
        self.loader = MarketDataLoader(data_dir)
        self.timeframe = timeframe
        self.ticks_path = ticks_path
        self.depth_path = depth_path
        self.use_gemma = use_gemma
        self._by_symbol: Dict[str, List] = {}
        self._bundles: Dict[str, Any] = {}
        self._preloaded = False

    def _preload(self) -> None:
        """Read both broker gzip streams ONCE; per-symbol calls are O(1)."""
        if self._preloaded:
            return
        self._preloaded = True
        all_candles: Dict[str, List] = {}
        try:
            deriv = self.loader.load_deriv(timeframe=self.timeframe)
            fp, _ = self.loader.load_fp_markets(timeframe=self.timeframe)
        except Exception:
            deriv, fp = [], []
        for c in list(deriv) + list(fp):
            all_candles.setdefault(c.symbol, []).append(c)
        for sym, candles in all_candles.items():
            candles.sort(key=lambda x: parse_time(x.open_time))
        self._by_symbol.update(all_candles)

    def _candles(self, symbol: str):
        self._preload()
        return self._by_symbol.get(symbol, [])

    def _bundle(self, symbol: str):
        if symbol not in self._bundles:
            ticks = (load_tick_trades(self.ticks_path, symbol=symbol)
                     if self.ticks_path else {})
            depth = (load_depth_signals(self.depth_path, symbol=symbol)
                     if self.depth_path else {})
            self._bundles[symbol] = build_signal_bundle(
                self._candles(symbol), symbol=symbol,
                tick_trades=ticks, depth=depth,
                use_gemma=self.use_gemma)
        return self._bundles[symbol]

    def _entry_index(self, symbol: str, entry_time: float) -> Optional[int]:
        candles = self._candles(symbol)
        if not candles:
            return None
        lo, hi, best = 0, len(candles) - 1, -1
        while lo <= hi:
            mid = (lo + hi) // 2
            if parse_time(candles[mid].open_time) <= entry_time:
                best = mid
                lo = mid + 1
            else:
                hi = mid - 1
        return best if best >= 30 else None

    def feature_window(self, symbol: str, entry_time: float
                       ) -> Optional[Tuple[List[float], List[float],
                                           List[float]]]:
        """Backwards-compatible (closes, highs, lows) window accessor."""
        win = self.signal_window(symbol, entry_time)
        if win is None:
            return None
        b = self._bundle(symbol)
        i = int(win["index"])
        return b.closes[: i + 1], b.highs[: i + 1], b.lows[: i + 1]

    def signal_window(self, symbol: str, entry_time: float
                      ) -> Optional[Dict[str, Any]]:
        """All 23 market features + signal source at the entry bar."""
        i = self._entry_index(symbol, entry_time)
        if i is None:
            return None
        b = self._bundle(symbol)
        if i >= b.n_bars:
            return None
        return {
            "index": i,
            "market_features": b.market_features[i],
            "orderflow": b.orderflow[i],
            "footprint": b.footprint[i],
            "regime": b.regimes[i],
            "agent_scores": b.agent_scores[i],
            "sources": b.sources,
        }

    def sources_summary(self) -> Dict[str, Any]:
        return {sym: b.sources for sym, b in self._bundles.items()}


# --------------------------------------------------------------------------
# Training
# --------------------------------------------------------------------------
def train_online(brain, trades: List[Trade],
                 align: MarketAlign) -> Tuple[int, int, Dict[str, Any]]:
    """One gradient step + loss-pattern update per settled trade."""
    trained, skipped = 0, 0
    for t in trades:
        win = align.signal_window(t.symbol, t.entry_time)
        if win is None:
            skipped += 1
            continue
        feats = features_for_brain(
            brain, win["market_features"], symbol=t.symbol)
        rr = market_return_for_trade(t)
        result = brain.online_learn_features(feats, rr, symbol=t.symbol)
        brain.learn_from_trade(
            symbol=t.symbol, regime=win["regime"], direction=t.direction,
            entry_type=t.entry_type or "CONFIRM",
            entry_quality=t.entry_quality, pnl=t.pnl, features=feats)
        if result.get("updated"):
            trained += 1
    return trained, skipped, brain.loss_guard.stats()


def train_offline(brain, trades: List[Trade], align: MarketAlign,
                  *, epochs: int = 30, batch_size: int = 32,
                  lr: float = 3e-3
                  ) -> Tuple[int, int, float, Dict[str, Any]]:
    """Mini-batch Adam refinement from full trade feature vectors."""
    X: List[np.ndarray] = []
    y: List[float] = []
    skipped = 0
    for t in trades:
        win = align.signal_window(t.symbol, t.entry_time)
        if win is None:
            skipped += 1
            continue
        feats = features_for_brain(
            brain, win["market_features"], symbol=t.symbol)
        rr = market_return_for_trade(t)
        X.append(np.asarray(feats, dtype=float))
        y.append(1.0 if rr > 0 else 0.0)
        brain.learn_from_trade(
            symbol=t.symbol, regime=win["regime"], direction=t.direction,
            entry_type=t.entry_type or "CONFIRM",
            entry_quality=t.entry_quality, pnl=t.pnl, features=feats)
    if not X:
        return 0, skipped, 0.0, brain.loss_guard.stats()
    X = np.asarray(X)
    y = np.asarray(y)
    # Losing trades get one extra sample, so the batch objective explicitly
    # emphasises loss-associated setups rather than only average accuracy.
    loss_idx = np.where(y == 0.0)[0]
    if len(loss_idx):
        X = np.concatenate((X, X[loss_idx]), axis=0)
        y = np.concatenate((y, y[loss_idx]), axis=0)
    rng = np.random.default_rng(0)
    last_loss = 0.0
    for epoch in range(epochs):
        order = rng.permutation(len(X))
        for start in range(0, len(X), batch_size):
            idx = order[start:start + batch_size]
            for m in brain.ensemble.members:
                m.model.optimizer.lr = lr
                if hasattr(m.model, "_online_opt"):
                    m.model._online_opt.lr = lr
                last_loss = m.model.train_step(X[idx], y[idx], rng=rng)
    return len(X), skipped, last_loss, brain.loss_guard.stats()


def _collect_trade_paths(spec: str) -> List[str]:
    paths: List[str] = []
    if os.path.isdir(spec):
        for pattern in ("**/*.csv", "**/*.csv.gz", "**/*.gz",
                        "**/*.json", "**/*.txt"):
            paths.extend(glob.glob(os.path.join(spec, pattern),
                                   recursive=True))
    else:
        paths.extend(glob.glob(spec))
        if not paths and os.path.isfile(spec):
            paths.append(spec)
    return sorted({p for p in paths if os.path.isfile(p)})


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--trades", default=TRADE_HISTORY_DIR,
                    help="trade history file/glob or directory")
    ap.add_argument("--data", default=MARKET_DATA_DIR,
                    help="market data dir for full feature alignment")
    ap.add_argument("--timeframe", default="M5")
    ap.add_argument("--mode", choices=["online", "offline"],
                    default="online")
    ap.add_argument("--lr", type=float, default=1e-3)
    ap.add_argument("--epochs", type=int, default=20)
    ap.add_argument("--batch-size", type=int, default=32)
    ap.add_argument("--max-trades", type=int, default=0)
    ap.add_argument("--in", dest="in_dir", default=None)
    ap.add_argument("--out", default=None)
    ap.add_argument("--ticks", default=TICK_TRADES_PATH)
    ap.add_argument("--depth", default=DEPTH_SNAPSHOTS_PATH)
    ap.add_argument("--gemma", action="store_true")
    args = ap.parse_args()

    paths = _collect_trade_paths(args.trades)
    if not paths:
        print(f"ERROR: no trade files found at {args.trades}. "
              "Run scripts/link_all.sh first.")
        return 1
    print(f"Found {len(paths)} trade file(s).")

    all_trades: List[Trade] = []
    for p in sorted(paths):
        ts = load_trade_file(p)
        if ts:
            print(f"  {os.path.relpath(p):44} trades={len(ts)}")
        all_trades.extend(ts)
    all_trades = [t for t in all_trades if t.symbol in SYMBOL_UNIVERSE]
    if args.max_trades > 0:
        all_trades = all_trades[:args.max_trades]
    print(f"\nTotal trades (universe symbols): {len(all_trades)}")
    if not all_trades:
        print("ERROR: no trades mapped to the symbol universe.")
        return 1

    in_dir = args.in_dir or unified_brain_dir()
    out_dir = args.out or in_dir
    brain = load_unified(in_dir)
    if brain is None:
        print(f"ERROR: no unified brain at {in_dir}. "
              "Run scripts/train_unified.py first.")
        return 1
    print(f"Loaded unified brain: {len(brain.ensemble.members)} members, "
          f"{len(brain.symbol_ids)} symbols | "
          f"online_updates so far={brain.online_updates}")
    brain.nn_online_lr = args.lr
    brain.online_enabled = True
    all_trades = [t for t in all_trades if t.symbol in brain.symbol_ids]

    align = MarketAlign(
        args.data, args.timeframe,
        ticks_path=args.ticks, depth_path=args.depth,
        use_gemma=bool(args.gemma or GEMMA_ENABLED))
    t0 = time.time()
    loss = 0.0
    if args.mode == "online":
        trained, skipped, guard = train_online(brain, all_trades, align)
        print(f"\nOnline trade training: {trained} trades trained, "
              f"{skipped} skipped (no market data / too early)")
        print(f"  brain.online_updates now = {brain.online_updates}")
    else:
        trained, skipped, loss, guard = train_offline(
            brain, all_trades, align, epochs=args.epochs,
            batch_size=args.batch_size, lr=args.lr)
        print(f"\nOffline batch training: {trained} weighted samples, "
              f"{skipped} skipped | final_loss={loss:.4f}")
        brain.online_updates += len(all_trades) - skipped
    dt = time.time() - t0
    print(f"done in {dt:.1f}s | loss guard={guard}")

    os.makedirs(out_dir, exist_ok=True)
    path = save_unified(out_dir, brain)
    report = {
        "version": SIGNAL_DATA_VERSION,
        "stage": f"real_trade_{args.mode}_training",
        "mode": args.mode,
        "trade_files": len(paths),
        "trades_loaded": len(all_trades),
        "trained": trained,
        "skipped": skipped,
        "final_loss": loss,
        "lr": args.lr,
        "epochs": args.epochs if args.mode == "offline" else 0,
        "elapsed_s": round(dt, 3),
        "loss_guard": guard,
        "signal_sources": align.sources_summary(),
        "online_updates_total": brain.online_updates,
    }
    for name in (f"trade_report_{args.mode}.json", "trade_report.json"):
        with open(os.path.join(out_dir, name), "w") as fh:
            json.dump(report, fh, indent=2, default=str)
    print(f"Refined brain saved: {path}")
    return 0


