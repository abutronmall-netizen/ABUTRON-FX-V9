"""Train the brain from REAL trade history with full causal features.

Each settled trade is aligned to the market-data candle at entry. The 23
market feature slots are generated by ``brain.signals.build_signal_bundle``
(order flow, footprint, regime and agent/Gemma scores), so the brain learns
from the same features it sees live. The trade's direction is converted to a
market-up/down label correctly for SELL trades. Every loss also updates the
explicit ``LossPatternGuard``; every win can clear a previously blocked
pattern.

Two modes are supported:
  --mode online  : one causal gradient step + loss-guard update per trade
  --mode offline : mini-batch Adam refinement over all trade features

Usage:
    PYTHONPATH=src python -m scripts.train_from_trades \
        --trades data/links/trade-history \
        --data data/links/market-data \
        --mode online --lr 1e-3 \
        [--in data/brains/unified_m5] [--out data/brains/unified_m5]

Tick/depth evidence is optional. Without it, explicitly-labelled OHLCV
proxies are used; see docs/INSTALL_AND_LINK.md for the accepted schemas.
"""
